#!/bin/bash
PGPASSWORD="$POSTGRESQL_POSTGRES_PASSWORD" psql -U postgres -d "$POSTGRESQL_DATABASE" -v approle="$POSTGRESQL_USERNAME" -v ON_ERROR_STOP=1 <<'SQL'
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO :"approle";
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO :"approle";
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO :"approle";
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO :"approle";
SQL
